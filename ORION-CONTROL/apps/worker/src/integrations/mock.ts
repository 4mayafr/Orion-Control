/**
 * Mock integration.
 *
 * Produces the same shapes as a real retrieval, but every payload is marked
 * `source: 'simulated'` and carries a warning. This is how the full
 * website → queue → worker → result pipeline can be tested without a Discord
 * token or a target bot.
 */

import { createSimulatedSnapshot, type TaskType } from '@orion/shared';
import type { Logger } from '../logger.js';
import { abortableDelay } from '../util.js';
import { IntegrationError, type IntegrationAdapter, type IntegrationRequest, type IntegrationResult } from './types.js';

export class MockIntegrationAdapter implements IntegrationAdapter {
  readonly name = 'simulated-adapter';
  readonly mode = 'mock' as const;

  constructor(private readonly logger: Logger) {}

  async execute(request: IntegrationRequest): Promise<IntegrationResult> {
    // A little latency keeps the UI's task states realistic.
    await abortableDelay(350 + Math.floor(Math.random() * 650), request.signal);
    const retrievedAt = new Date().toISOString();

    switch (request.type) {
      case 'statistics.retrieve':
        return this.statistics(retrievedAt);
      case 'players.retrieve':
        return this.players(retrievedAt);
      case 'discord.channel_check':
        return this.channelCheck();
      default:
        throw new IntegrationError(
          `The simulated adapter does not support task type "${request.type}".`,
          'UNSUPPORTED_TASK_TYPE',
          false,
        );
    }
  }

  private statistics(retrievedAt: string): IntegrationResult {
    const snapshot = createSimulatedSnapshot({
      retrievedAt,
      seed: Date.now() % 1_000_000,
    });
    this.logger.info('Generated a simulated statistics snapshot (no Discord traffic).');
    return {
      rawResponse: JSON.stringify(
        {
          adapter: this.name,
          simulated: true,
          note: 'Mock integration output. Not an Orion Drift read-out.',
          snapshot,
        },
        null,
        2,
      ),
      parsedResponse: snapshot,
      notes: [
        'Simulated integration: no Discord message was sent. Set INTEGRATION_MODE=channel to use the relay.',
      ],
    };
  }

  private players(retrievedAt: string): IntegrationResult {
    const snapshot = createSimulatedSnapshot({ retrievedAt, seed: Date.now() % 1_000_000 });
    const directory = {
      source: 'simulated' as const,
      retrievedAt,
      players: snapshot.players,
      notes: 'Simulated player directory generated by the mock adapter.',
    };
    return {
      rawResponse: JSON.stringify({ adapter: this.name, simulated: true, directory }, null, 2),
      parsedResponse: directory,
      notes: ['Simulated player directory; no Discord traffic was generated.'],
    };
  }

  private channelCheck(): IntegrationResult {
    const diagnostics = {
      simulated: true,
      connected: false,
      note: 'Mock integration: no Discord client was contacted. Configure INTEGRATION_MODE=channel and Discord credentials to run real diagnostics.',
      checkedAt: new Date().toISOString(),
    };
    return {
      rawResponse: JSON.stringify(diagnostics, null, 2),
      parsedResponse: diagnostics,
      notes: ['Mock diagnostics only; Discord was not contacted.'],
    };
  }
}

export function supportedMockTypes(): TaskType[] {
  return ['statistics.retrieve', 'players.retrieve', 'discord.channel_check'];
}
